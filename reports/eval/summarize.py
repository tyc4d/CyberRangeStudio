"""Build reports/eval/eval-run-summary.md from reports/eval/runs/*/run-*/ (no LLM)."""
import collections, json, pathlib, subprocess
ROOT = pathlib.Path(__file__).resolve().parents[2]
R = ROOT / "reports/eval/runs"
def load(p):
    try: return json.loads(p.read_text())
    except Exception: return None
rows, total, n_err = [], 0.0, 0
for d in sorted(R.glob("*/run-*")):
    m = load(d / "meta.json") or {}
    ir, dep, topo, iac = (load(d / f) for f in ("01-ir.json", "02-dependencies.json", "03-topology.json", "04-iac-report.json"))
    total += m.get("llm_cost_usd", 0) or 0
    if m.get("status") != "ok": n_err += 1
    rep = collections.Counter(a.get("reproducibility") for a in (dep or {}).get("actions", []))
    miss = (dep or ir or {}).get("missing_items", [])
    blk_items = [x for x in miss if x.get("status") == "open" and x.get("severity") == "blocker"]
    iac_dep = None if iac is None else bool(iac.get("deployable"))
    rows.append([d.parent.name, d.name[4:], m.get("status", "missing"),
                 len(ir["actions"]) if ir else "-",
                 len(ir["hosts"]) if ir else "-",
                 len(topo["hosts"]) if topo else "-",
                 len(ir["missing_items"]) if ir else "-",
                 len(miss) if dep else "-",
                 len(blk_items) if dep else "-",
                 "-" if iac is None else ("no" if iac_dep else f"yes ({len(iac.get('blockers', []))})"),
                 " ".join(f"{k}:{v}" for k, v in sorted(rep.items(), key=lambda kv: str(kv[0]))) or "-",
                 (dep or {}).get("fidelity", "-"),
                 f"{m.get('llm_cost_usd', 0):.4f}", m.get("duration_s", "-"),
                 "; ".join(m.get("errors", []))[:160].replace("|", "/") or ""])
sha = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
hdr = ["report", "run", "status", "#steps (IR actions)", "#hosts IR", "#hosts env plan", "#missing IR (mod 1)", "#missing after mod 4", "#open blocker-severity items", "IaC blocked (#blockers)", "reproducibility per step", "fidelity", "LLM $", "sec", "errors"]
out = ["# eval-run summary", "",
       f"- Code: branch `agent/eval-run`, product code at `fbfd050` (= main + eval-cti fixtures + brief). Generated by `reports/eval/summarize.py`.",
       f"- Runs: {len(rows)}; not ok: {n_err}; total LLM est. cost: ${total:.4f} (Budget Manager ledger estimate, conservative prices).", ""]
out += ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
(ROOT / "reports/eval/eval-run-table.md").write_text("\n".join(out) + "\n")
print("\n".join(out))

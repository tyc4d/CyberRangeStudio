# Never produced by this project; listed so a reader does not expect them.
NOT_GENERATED_IAC = (
    "infrastructure/terraform/ — not generated: this project deploys with Docker Compose "
    "(and libvirt for VMs); no Terraform exists to export. Not needed to rebuild the containers.",
    "infrastructure/ansible/ — not generated: this project has no Ansible playbooks; "
    "not needed to rebuild the containers.",
)

# --- secret handling ---------------------------------------------------------
_SECRET_KEY_RE = re.compile(
    r"(?:^|[_\-.])(password|passwd|pwd|passphrase|secret|secrets|token|tokens|api[_-]?key|apikey|"
    r"access[_-]?key|secret[_-]?key|private[_-]?key|client[_-]?secret|cookie|cookies|"
    r"credential|credentials|auth[_-]?token|bearer)(?:$|[_\-.])",
    re.IGNORECASE,
)
_RUNTIME_REF_RE = re.compile(r"^\$\{[A-Z][A-Z0-9_]*(?::?[-?][^${}]*)?\}$")
# High-confidence secret material: always redacted from text and fatal if found at the end.
_SECRET_VALUE_PATTERNS = (
    re.compile(r"-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----[\s\S]*?(?:-----END [A-Z0-9 ]*PRIVATE KEY-----|$)"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"\bgh[pousr]_[A-Za-z0-9]{36,}\b"),
    re.compile(r"\bgithub_pat_[A-Za-z0-9_]{40,}\b"),
    re.compile(r"\bsk-(?:ant-|proj-)?[A-Za-z0-9_-]{20,}\b"),
    re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b"),
    re.compile(r"(?i)\bbearer\s+[A-Za-z0-9._~+/-]{16,}=*"),
    re.compile(r"PVEAPIToken=[^\s'\"]+"),
)
# Free-text "password=xyz" / "token: xyz" — redact the value, keep the label. Deploy-time
# references (${...}) and <placeholders> are not values.
_INLINE_SECRET_RE = re.compile(
    r"(?i)\b(password|passwd|pwd|passphrase|token|secret|api[_-]?key)(\s*[:=]\s*)(?!\$\{|<|\[REDACTED\])([^\s'\",;&]+)"
)
_ENV_REF_RE = re.compile(r"\$\{([A-Z][A-Z0-9_]*)(?:(:?[-?])([^}]*))?\}")


class ExportError(RuntimeError):
    """The bundle cannot be produced safely (e.g. a secret would be written)."""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _env_secret_values() -> list[str]:
    """Literal values of secret-looking variables in the API process environment."""
    values = {config.OPENAI_API_KEY} if getattr(config, "OPENAI_API_KEY", "") else set()
    for key, value in os.environ.items():
        if value and _SECRET_KEY_RE.search(key):
            values.add(value)
    # Short values (e.g. "1", "true") would match everywhere and are not credentials.
    return sorted((v for v in values if len(v) >= 8), key=len, reverse=True)


def redact_text(text: str, env_secrets: list[str] | None = None) -> str:
    for secret in env_secrets if env_secrets is not None else _env_secret_values():
        text = text.replace(secret, REDACTED)
    for pattern in _SECRET_VALUE_PATTERNS:
        text = pattern.sub(REDACTED, text)
    return _INLINE_SECRET_RE.sub(lambda m: m.group(1) + m.group(2) + REDACTED, text)


def redact(obj: Any, env_secrets: list[str] | None = None, _under_secret: bool = False) -> Any:
    """Deep copy with secret-named fields and secret-looking text replaced by [REDACTED]."""
    env_secrets = _env_secret_values() if env_secrets is None else env_secrets
    if isinstance(obj, dict):
        out = {}
        for key, value in obj.items():
            secret_key = isinstance(key, str) and bool(_SECRET_KEY_RE.search(key))
            out[key] = redact(value, env_secrets, _under_secret or secret_key)
        return out
    if isinstance(obj, list):
        return [redact(v, env_secrets, _under_secret) for v in obj]
    if isinstance(obj, str):
        if _RUNTIME_REF_RE.fullmatch(obj):
            return obj  # deploy-time reference, not a value
        if _under_secret:
            return REDACTED if obj else obj
        return redact_text(obj, env_secrets)
    if _under_secret and isinstance(obj, (int, float)) and not isinstance(obj, bool):
        return REDACTED
    return obj


def find_secrets(text: str, env_secrets: list[str] | None = None) -> list[str]:
    """Names of secret indicators present in ``text`` (empty = clean). Never returns the value."""
    hits = []
    for secret in env_secrets if env_secrets is not None else _env_secret_values():
        if secret in text:
            hits.append("process-environment secret value")
    for pattern in _SECRET_VALUE_PATTERNS:
        if pattern.search(text):
            hits.append(f"pattern {pattern.pattern[:32]}")
    return hits


# --- collection ---------------------------------------------------------------
class _Bundle:
    def __init__(self, scenario_id: str):
        self.scenario_id = scenario_id
        self.files: dict[str, tuple[bytes, str]] = {}
        self.blocking: list[str] = []      # missing items that prevent a full rebuild
        self.informational: list[str] = []  # listed in missing_for_rebuild, not blocking
        self.notes: list[str] = []          # README-only remarks (omitted descriptors etc.)
        self.images: list[str] = []
        self.env_vars: list[tuple[str, str, str]] = []

    def add_json(self, path: str, obj: Any, generated_by: str) -> None:
        self.add(path, (json.dumps(obj, ensure_ascii=False, indent=2, sort_keys=False) + "\n").encode("utf-8"),
                 generated_by)

    def add(self, path: str, data: bytes, generated_by: str) -> None:
        if path in self.files or path == "manifest.json":
            raise ExportError(f"duplicate bundle path {path}")
        self.files[path] = (data, generated_by)


def _scenario(b: _Bundle, ir: dict[str, Any], env_secrets: list[str]) -> None:
    safe_ir = redact(ir, env_secrets)
    b.add_json("scenario/scenario.json", safe_ir, GEN_IR)
    b.add("scenario/scenario.yaml",
          yaml.safe_dump(safe_ir, sort_keys=False, allow_unicode=True).encode("utf-8"), GEN_IR)
    chain = {"scenario_id": b.scenario_id,
             "source": "Scenario IR actions + relations (the described attack chain, not a validation result)",
             "actions": safe_ir.get("actions", []) or [],
             "relations": safe_ir.get("relations", []) or []}
    if safe_ir.get("flow") is not None:
        chain["flow"] = safe_ir["flow"]
    b.add_json("scenario/attack-chain.json", chain, GEN_IR)


def _plan_report(ir: dict[str, Any], scenario_id: str) -> Optional[dict[str, Any]]:
    plan = ir.get("environment_plan")
    if not plan:
        return None
    try:
        _, report = generator.inspect_plan(plan, scenario_id)
        return report
    except Exception:  # an invalid plan simply yields no report
        return None


def _missing_hosts(b: _Bundle, report: Optional[dict[str, Any]]) -> None:
    if report is None:
        b.blocking.append("environment plan: the scenario has no valid environment plan (module 5), "
                          "so no deployable environment exists to export")
        return
    vm_hosts = set()
    for vm in report.get("vms", []) or []:
        host = vm.get("host_id")
        vm_hosts.add(host)
        b.blocking.append(f"VM image for host {host} (runtime=vm): not exportable/not bundled — "
                          f"{vm.get('reason') or 'VM guest image must be supplied separately'}")
    for nd in report.get("not_deployed_hosts", []) or []:
        b.blocking.append(f"image for host {nd.get('host_id')}: none available, host is not deployed — "
                          f"{nd.get('reason')}")
    for comp in report.get("components", []) or []:
        host = comp.get("host_id")
        if comp.get("deployable", True) or comp.get("skipped") or host in vm_hosts:
            continue
        b.blocking.append(f"image for host {host}: cannot be resolved to a deployable image — "
                          f"{comp.get('reason') or comp.get('image_hint') or 'unsupported component'}")


def _infrastructure(b: _Bundle) -> None:
    sid = b.scenario_id
    try:
        gen = generator.get_generated(sid)
    except FileNotFoundError:
        b.blocking.append("infrastructure/docker-compose.yml: not generated yet "
                          "(run IaC generation for this scenario before exporting)")
        return
    except generator.PlanError as exc:
        b.blocking.append(f"infrastructure/docker-compose.yml: generated file is stale or invalid "
                          f"and was not exported — {exc}")
        return

    compose = gen["compose"]
    try:
        parsed = yaml.safe_load(compose)
    except yaml.YAMLError as exc:  # generator guarantees valid YAML; fail closed anyway
        raise ExportError(f"generated compose is not valid YAML: {exc}") from exc
    services = (parsed or {}).get("services") or {}
    needs_template = any(isinstance(s.get("build"), dict) for s in services.values())
    if needs_template:
        if compose.count(_GEN_BUILD_CONTEXT) < 1:
            b.blocking.append("local build context: compose builds an image from an unrecognised context; "
                              "build context not bundled")
        elif not _TEMPLATE_DIR.is_dir():
            b.blocking.append(f"local build context {_TEMPLATE_DIR.name}: template directory missing "
                              "from this checkout")
        else:
            compose = compose.replace(_GEN_BUILD_CONTEXT, _BUNDLE_BUILD_CONTEXT)
            for item in sorted(_TEMPLATE_DIR.iterdir()):
                if item.is_file() and not item.is_symlink():
                    b.add(f"infrastructure/templates/demo-app/{item.name}", item.read_bytes(), GEN_TEMPLATE)
            b.notes.append("docker-compose.yml: the only change from the generator output is the local "
                           f"build context path (`{_GEN_BUILD_CONTEXT}` -> `{_BUNDLE_BUILD_CONTEXT}`) "
                           "so it resolves inside this bundle.")
    generated_by = GEN_IAC + (" (build context path relocated by app.poc.export)" if needs_template else "")
    b.add("infrastructure/docker-compose.yml", compose.encode("utf-8"), generated_by)
    b.add_json("infrastructure/iac-report.json", gen["report"], GEN_IAC)

    b.images = sorted({s["image"] for s in services.values() if s.get("image") and not s.get("build")})
    seen: dict[str, tuple[str, str, str]] = {}
    for name, op, arg in _ENV_REF_RE.findall(compose):
        if name not in seen:
            seen[name] = (name, op, arg)
    b.env_vars = list(seen.values())
    b.add("infrastructure/.env.example", _env_example(b.env_vars).encode("utf-8"), GEN_EXPORT)


def _env_example(env_vars: list[tuple[str, str, str]]) -> str:
    lines = [
        "# Placeholders for every ${VAR} read by docker-compose.yml. Copy to .env and fill in.",
        "# This file never contains a real secret. Generate fresh random values for secrets;",
        "# never reuse production credentials. Defaults shown are the generator's non-secret defaults.",
        "",
    ]
    if not env_vars:
        lines.append("# (docker-compose.yml reads no variables)")
    for name, op, arg in env_vars:
        secret = bool(_SECRET_KEY_RE.search(name))
        if secret or "?" in op:
            lines.append(f"# REQUIRED{' secret' if secret else ''}: set at deploy time"
                         + (" — generate a fresh random value" if secret else ""))
            lines.append(f"{name}=")
        elif "-" in op:
            lines.append("# optional; default used when unset")
            lines.append(f"{name}={arg}")
        else:
            lines.append(f"{name}=")
    return "\n".join(lines) + "\n"


def _validation(b: _Bundle, env_secrets: list[str]) -> list[dict[str, Any]]:
    sid = b.scenario_id
    plan = poc_store.get_plan(sid)
    if plan:
        b.add_json("validation/validation-plan.json", redact(plan, env_secrets), GEN_PLAN)
    else:
        b.notes.append("validation/validation-plan.json omitted: no ValidationPlan recorded (POST /api/poc/{id}/plan).")
    manifest = poc_store.get_manifest(sid)
    if manifest:
        b.add_json("validation/poc-manifest.json", redact(manifest, env_secrets), GEN_CANDIDATES)
    else:
        b.notes.append("validation/poc-manifest.json omitted: no PoC discovery recorded.")
    runs = redact(poc_store.get_runs(sid), env_secrets)
    chain = poc_store.get_chain(sid)
    if runs or chain:
        b.add_json("validation/results.json",
                   {"scenario_id": sid, "execution_results": runs,
                    "chain_validation": redact(chain, env_secrets) if chain else None},
                   GEN_RUNS)
    else:
        b.notes.append("validation/results.json omitted: no PoC execution or chain validation recorded.")
    fidelity = None
    try:
        from app.poc import service
        fidelity = service.report(sid)
    except NotImplementedError:
        b.notes.append("validation/fidelity-report.json omitted: fidelity report not implemented in this build.")
    except Exception as exc:  # no data yet / unknown scenario for the report
        b.notes.append(f"validation/fidelity-report.json omitted: report unavailable ({type(exc).__name__}).")
    if fidelity:
        b.add_json("validation/fidelity-report.json", redact(fidelity, env_secrets), GEN_FIDELITY)
    return runs


def _evidence_index(b: _Bundle, runs: list[dict[str, Any]]) -> None:
    root = config.DATA_DIR.resolve()
    items = []
    for run in runs:
        for ev in run.get("evidence", []) or []:
            raw = str(ev.get("path") or "")
            entry = {"action_id": run.get("action_id"), "run_status": run.get("status"),
                     "kind": ev.get("kind"), "path": raw, "sha256": ev.get("sha256"),
                     "redacted": ev.get("redacted"), "note": ev.get("note"),
                     "present_on_exporting_host": False, "sha256_verified": False}
            try:
                p = Path(raw)
                p = (p if p.is_absolute() else root / p).resolve()
                inside = p == root or root in p.parents
                if raw and inside and p.is_file():
                    entry["present_on_exporting_host"] = True
                    h = hashlib.sha256()
                    with p.open("rb") as f:
                        for chunk in iter(lambda: f.read(1 << 20), b""):
                            h.update(chunk)
                    entry["sha256_verified"] = h.hexdigest() == ev.get("sha256")
            except OSError:
                pass
            items.append(entry)
    b.add_json("evidence/evidence-index.json", {
        "scenario_id": b.scenario_id,
        "raw_evidence_included": False,
        "note": ("Index only. Raw evidence stays under the exporting host's DATA_DIR and is not copied "
                 "into the bundle (it may contain target data). sha256_verified compares the stored file "
                 "with the hash recorded at execution time."),
        "items": items,
    }, GEN_EXPORT)



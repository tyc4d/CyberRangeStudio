# --- secret handling ---------------------------------------------------------
_SECRET_KEY_RE = re.compile(
    r"(?:^|[_\-.])(password|passwd|pwd|passphrase|secret|secrets|token|tokens|api[_-]?key|apikey|"
    r"access[_-]?key|secret[_-]?key|private[_-]?key|client[_-]?secret|cookie|cookies|"
    r"credential|credentials|auth[_-]?token|bearer)(?:$|[_\-.])",
    re.IGNORECASE,
)
# High-confidence secret material: always redacted from text and fatal if found at the end.
_SECRET_VALUE_PATTERNS = (
    re.compile(r"-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----[\s\S]*?(?:-----END [A-Z0-9 ]*PRIVATE KEY-----|$)"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"\bgh[pousr]_[A-Za-z0-9]{36,}\b"),
    re.compile(r"\bgithub_pat_[A-Za-z0-9_]{40,}\b"),
    re.compile(r"\bsk-(?:ant-|proj-)?[A-Za-z0-9_-]{20,}\b"),
    re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b"),
    re.compile(r"(?i)\bbearer\s+[A-Za-z0-9._~+/-]{16,}=*"),
    re.compile(r"PVEAPIToken=[^\s'\"]+"),
)
# Free-text "password=xyz" / "token: 'xyz'" / apiKey="xyz" — redact the value, keep the label.
# Quoted values run to the matching quote (or end of line); bare values include apostrophes so
# a quote cannot cut the scan short. Deploy-time references (${...}) and <placeholders> are kept.
_INLINE_LABEL = (r"[A-Za-z0-9_.\-]*?(?:password|passwd|pwd|passphrase|token|secret|api[_\-]?key|apikey|"
                 r"access[_\-]?key|credential)[A-Za-z0-9_\-]*")
_INLINE_SECRET_RE = re.compile(
    r"(?i)(?<![A-Za-z0-9_{.\-])(" + _INLINE_LABEL + r")([ \t]*[:=][ \t]*)"
    r"(?:(['\"])((?:(?!\3)[^\n])*)(\3?)|(?!\$\{|<)([^\s\",;&]+))")
# URL userinfo: everything between "scheme://" and the LAST "@" of the authority (stops at / ? # or
# whitespace). Quotes and colon-less token-as-username forms are covered; the whole userinfo is redacted.
_URL_USERINFO_RE = re.compile(r"(?i)\b([a-z][a-z0-9+.\-]*://)([^\s/?#\"<>\\]*)@")
# Query / fragment parameters (?access_token=..., &%61pi_key=..., #id_token=...). The parameter NAME is
# percent-decoded before it is classified; the value runs to & # or whitespace (apostrophes included).
_QUERY_PARAM_RE = re.compile(r"([?&#;])([^=&#\s\"<>?;]+)=([^&#\s\"<>]*)")
_QUERY_SECRET_NAME_RE = re.compile(
    r"token|secret|pass|pwd|api[_\-]?key|apikey|access[_\-]?key|auth|sig|session|credential|cookie|key",
    re.IGNORECASE)
_REF_HEAD_RE = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)(:?[-?+=])?", re.S)
_SAFE_SECRET_REF_RE = re.compile(r"(?:\$\{[A-Za-z_][A-Za-z0-9_]*(?::?[-?+=](?:\[REDACTED\])?)?\})+")
_SECRET_VAR_NAME_RE = re.compile(r"PASS|PWD|SECRET|TOKEN|API_?KEY|ACCESS_?KEY|PRIVATE_?KEY|CREDENTIAL|COOKIE",
                                 re.IGNORECASE)
_ENV_REF_RE = re.compile(r"\$\{([A-Z][A-Z0-9_]*)(?:(:?[-?])([^}]*))?\}")


class ExportError(RuntimeError):
    """The bundle cannot be produced safely (e.g. a secret would be written)."""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _env_secret_values() -> list[str]:
    """Literal values of secret-looking variables in the API process environment."""
    values = {config.OPENAI_API_KEY} if getattr(config, "OPENAI_API_KEY", "") else set()
    for key, value in os.environ.items():
        if value and _is_secret_key(key):
            values.add(value)
    # Short values (e.g. "1", "true") would match everywhere and are not credentials.
    return sorted((v for v in values if len(v) >= 8), key=len, reverse=True)


def _matching_brace(text: str, open_idx: int) -> Optional[int]:
    depth = 0
    for i in range(open_idx, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return i
    return None


def _walk_refs(text: str, force: bool = False) -> str:
    """Rewrite ${...} interpolations (nesting-aware).

    force=True (inside a secret-named field): every branch argument (:- - := = :+ + :? ?) becomes
    [REDACTED]. Otherwise a secret-named variable's value branches (- = +) are redacted; its ``?``
    branch is an error message and is redacted too, since it may carry the literal. Arguments of
    non-secret refs are walked recursively, so a nested secret ref is still caught.
    """
    out: list[str] = []
    i = 0
    while True:
        j = text.find("${", i)
        if j < 0:
            out.append(text[i:])
            break
        out.append(text[i:j])
        k = _matching_brace(text, j + 1)
        if k is None:  # unbalanced: nothing structured left to keep
            out.append(REDACTED if force else text[j:])
            break
        inner = text[j + 2:k]
        m = _REF_HEAD_RE.match(inner)
        if not m:
            out.append("${" + _walk_refs(inner, force) + "}")
        else:
            name, op = m.group(1), m.group(2) or ""
            arg = inner[m.end():]
            if arg and arg != REDACTED and (force or (op and _SECRET_VAR_NAME_RE.search(name))):
                arg = REDACTED
            elif arg:
                arg = _walk_refs(arg, force)
            out.append("${" + name + op + arg + "}")
        i = k + 1
    return "".join(out)


def _secret_query_param(m: re.Match) -> bool:
    """True if this ?name=value carries a secret-named parameter with a value that is not redacted."""
    value = m.group(3)
    return bool(value) and value != REDACTED and bool(_QUERY_SECRET_NAME_RE.search(unquote(m.group(2))))


def _inline_value_unsafe(m: re.Match) -> bool:
    if m.group(3) is not None:  # quoted
        value = m.group(4)
        return bool(value) and value != REDACTED and not value.startswith("${")
    bare = m.group(6)
    return (bare is not None and not bare.startswith(REDACTED)
            and bare.strip("`'.)").lower() not in {"true", "false", "null", "none"})


def _redact_inline(m: re.Match) -> str:
    if not _inline_value_unsafe(m):
        return m.group(0)
    if m.group(3) is not None:
        return m.group(1) + m.group(2) + m.group(3) + REDACTED + m.group(5)
    return m.group(1) + m.group(2) + REDACTED


def _redact_urls(text: str) -> str:
    text = _URL_USERINFO_RE.sub(
        lambda m: m.group(0) if m.group(2) == REDACTED else m.group(1) + REDACTED + "@", text)
    return _QUERY_PARAM_RE.sub(
        lambda m: m.group(1) + m.group(2) + "=" + REDACTED if _secret_query_param(m) else m.group(0), text)


def redact_text(text: str, env_secrets: list[str] | None = None) -> str:
    for secret in env_secrets if env_secrets is not None else _env_secret_values():
        text = text.replace(secret, REDACTED)
    for pattern in _SECRET_VALUE_PATTERNS:
        text = pattern.sub(REDACTED, text)
    text = _redact_urls(text)
    text = _walk_refs(text)
    return _INLINE_SECRET_RE.sub(_redact_inline, text)


def _redact_secret_field(value: str) -> str:
    """A string inside a secret-named field: keep only bare interpolation structure, else redact."""
    if not value or value == REDACTED:
        return value
    rewritten = _walk_refs(value, force=True)
    return rewritten if _SAFE_SECRET_REF_RE.fullmatch(rewritten) else REDACTED


# Mapping keys allowed to stay as-is INSIDE a secret-named subtree (field names, not data).
_BENIGN_SECRET_SUBKEYS = frozenset({
    "id", "name", "type", "kind", "username", "user", "user_name", "login", "account", "password", "passwd",
    "pwd", "passphrase", "secret", "token", "value", "key", "api_key", "apikey", "access_key", "secret_key",
    "private_key", "client_id", "client_secret", "note", "notes", "description", "source", "host", "port",
    "service", "scope", "expires", "expires_at", "created_at", "issuer", "hash", "algorithm", "format", "redacted",
})
_REDACTED_KEY_RE = re.compile(r"\[REDACTED-key-\d+\]")


def _is_secret_key(key: Any) -> bool:
    """Secret-named field? Percent-decoded and camelCase-split before matching."""
    if not isinstance(key, str):
        return False
    decoded = unquote(key)
    snake = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", decoded)
    return bool(_SECRET_KEY_RE.search(decoded) or _SECRET_KEY_RE.search(snake))


def _key_allowed_under_secret(key: Any) -> bool:
    return isinstance(key, str) and (key.lower() in _BENIGN_SECRET_SUBKEYS or bool(_REDACTED_KEY_RE.fullmatch(key)))


def redact(obj: Any, env_secrets: list[str] | None = None, _under_secret: bool = False) -> Any:
    """Deep copy with secret-named fields, secret-looking text AND mapping keys redacted.

    Inside a secret-named subtree a key is kept only if it is a known field name; any other key
    (which may itself be the credential) becomes ``[REDACTED-key-<n>]``.
    """
    env_secrets = _env_secret_values() if env_secrets is None else env_secrets
    if isinstance(obj, dict):
        out: dict[Any, Any] = {}
        for n, (key, value) in enumerate(obj.items(), 1):
            secret_key = _is_secret_key(key)
            if isinstance(key, str):
                if _under_secret and not _key_allowed_under_secret(key):
                    new_key = f"[REDACTED-key-{n}]"
                else:
                    new_key = redact_text(key, env_secrets)
            else:
                new_key = REDACTED if _under_secret else key
            while new_key in out:
                new_key = f"[REDACTED-key-{n}-{len(out)}]" if _under_secret else f"{new_key}#{n}"
            out[new_key] = redact(value, env_secrets, _under_secret or secret_key)
        return out
    if isinstance(obj, list):
        return [redact(v, env_secrets, _under_secret) for v in obj]
    if isinstance(obj, str):
        return _redact_secret_field(obj) if _under_secret else redact_text(obj, env_secrets)
    if _under_secret and isinstance(obj, (int, float)) and not isinstance(obj, bool):
        return REDACTED
    return obj


def find_secrets(text: str, env_secrets: list[str] | None = None) -> list[str]:
    """Names of secret indicators present in ``text`` (empty = clean). Never returns the value.

    Text-level check, valid for any file (including the generator's compose, whose
    ``${CR_DB_PASSWORD:?set at deploy time}`` error messages are allowed here). Structured
    files are additionally checked field-by-field by :func:`find_field_secrets`.
    """
    hits = []
    for secret in env_secrets if env_secrets is not None else _env_secret_values():
        if secret in text:
            hits.append("process-environment secret value")
    for pattern in _SECRET_VALUE_PATTERNS:
        if pattern.search(text):
            hits.append(f"pattern {pattern.pattern[:32]}")
    if any(m.group(2) != REDACTED for m in _URL_USERINFO_RE.finditer(text)):
        hits.append("credentials in URL userinfo")
    if any(_secret_query_param(m) for m in _QUERY_PARAM_RE.finditer(text)):
        hits.append("secret-named URL query parameter")
    unescaped = text.replace('\\"', '"')  # JSON-escaped quotes delimit inline values too
    if any(_inline_value_unsafe(m) for m in _INLINE_SECRET_RE.finditer(unescaped)):
        hits.append("inline secret label with a value")
    for m in re.finditer(r"\$\{([A-Za-z_][A-Za-z0-9_]*)(:?[-+=])", text):
        if _SECRET_VAR_NAME_RE.search(m.group(1)):
            k = _matching_brace(text, m.start() + 1)
            arg = text[m.end():k] if k is not None else text[m.end():]
            if arg and arg != REDACTED:
                hits.append("literal value branch of a secret-named ${VAR...} reference")
                break
    return hits


def find_field_secrets(obj: Any, _under_secret: bool = False, _path: str = "") -> list[str]:
    """Field-aware check of parsed JSON/YAML: every secret-named field must hold nothing usable.

    Allowed under a secret-named key: empty, null, bool, [REDACTED], or bare interpolations whose
    branch arguments are all [REDACTED]. Anything else is reported (fail closed).
    """
    hits: list[str] = []
    if isinstance(obj, dict):
        for n, (key, value) in enumerate(obj.items()):
            if _under_secret and not _key_allowed_under_secret(key):
                hits.append(f"unredacted mapping key in secret-named field {_path}/#{n}")
            elif isinstance(key, str) and find_secrets(key, []):
                hits.append(f"secret material in mapping key {_path}/#{n}")
            shown = (isinstance(key, str) and re.fullmatch(r"[A-Za-z0-9_\-]{1,32}", key) is not None
                     and (_key_allowed_under_secret(key) or not _under_secret) and not find_secrets(key, []))
            hits += find_field_secrets(value, _under_secret or _is_secret_key(key),
                                       f"{_path}/{key if shown else '#' + str(n)}")
    elif isinstance(obj, list):
        for n, value in enumerate(obj):
            hits += find_field_secrets(value, _under_secret, f"{_path}/{n}")
    elif _under_secret:
        if isinstance(obj, str):
            if obj and obj != REDACTED and not _SAFE_SECRET_REF_RE.fullmatch(obj):
                hits.append(f"unredacted value in secret-named field {_path}")
        elif obj is not None and not isinstance(obj, bool):
            hits.append(f"unredacted value in secret-named field {_path}")
    return hits


def _structured_secrets(path: str, data: bytes) -> list[str]:
    """find_field_secrets for bundle JSON/YAML files; an unparsable structured file fails closed.

    The generator's docker-compose.yml is exempt (its secret-named env keys legitimately hold
    ``${CR_..._PASSWORD:?set at deploy time}``); it is covered by the text scan and by the
    generator's own forbidden-credential check.
    """
    if path == "infrastructure/docker-compose.yml" or not path.endswith((".json", ".yaml", ".yml")):
        return []
    try:
        text = data.decode("utf-8")
        obj = json.loads(text) if path.endswith(".json") else yaml.safe_load(text)
    except (UnicodeDecodeError, ValueError, yaml.YAMLError):
        return [f"cannot parse {path} to confirm it is secret-free"]
    return find_field_secrets(obj)


# --- collection ---------------------------------------------------------------
class _Bundle:
    def __init__(self, scenario_id: str):
        self.scenario_id = scenario_id
        self.files: dict[str, tuple[bytes, str]] = {}
        self.blocking: list[str] = []      # missing items that prevent a full rebuild
        self.informational: list[str] = []  # listed in missing_for_rebuild, not blocking
        self.notes: list[str] = []          # README-only remarks (omitted descriptors etc.)
        self.images: list[str] = []
        self.env_vars: list[tuple[str, str, str]] = []

    def add_json(self, path: str, obj: Any, generated_by: str) -> None:
        self.add(path, (json.dumps(obj, ensure_ascii=False, indent=2, sort_keys=False) + "\n").encode("utf-8"),
                 generated_by)

    def add(self, path: str, data: bytes, generated_by: str) -> None:
        if path in self.files or path == "manifest.json":
            raise ExportError(f"duplicate bundle path {path}")
        self.files[path] = (data, generated_by)


def _scenario(b: _Bundle, ir: dict[str, Any], env_secrets: list[str]) -> None:
    safe_ir = redact(ir, env_secrets)
    b.add_json("scenario/scenario.json", safe_ir, GEN_IR)
    b.add("scenario/scenario.yaml",
          yaml.safe_dump(safe_ir, sort_keys=False, allow_unicode=True).encode("utf-8"), GEN_IR)
    chain = {"scenario_id": b.scenario_id,
             "source": "Scenario IR actions + relations (the described attack chain, not a validation result)",
             "actions": safe_ir.get("actions", []) or [],
             "relations": safe_ir.get("relations", []) or []}
    if safe_ir.get("flow") is not None:
        chain["flow"] = safe_ir["flow"]
    b.add_json("scenario/attack-chain.json", chain, GEN_IR)


def _plan_report(ir: dict[str, Any], scenario_id: str) -> Optional[dict[str, Any]]:
    plan = ir.get("environment_plan")
    if not plan:
        return None
    try:
        _, report = generator.inspect_plan(plan, scenario_id)
        return report
    except Exception:  # an invalid plan simply yields no report
        return None


def _missing_hosts(b: _Bundle, report: Optional[dict[str, Any]]) -> None:
    if report is None:
        b.blocking.append("environment plan: the scenario has no valid environment plan (module 5), "
                          "so no deployable environment exists to export")
        return
    vm_hosts = set()
    for vm in report.get("vms", []) or []:
        host = vm.get("host_id")
        vm_hosts.add(host)
        b.blocking.append(f"VM image for host {host} (runtime=vm): not exportable/not bundled — "
                          f"{vm.get('reason') or 'VM guest image must be supplied separately'}")
    for nd in report.get("not_deployed_hosts", []) or []:
        b.blocking.append(f"image for host {nd.get('host_id')}: none available, host is not deployed — "
                          f"{nd.get('reason')}")
    for comp in report.get("components", []) or []:
        host = comp.get("host_id")
        if comp.get("deployable", True) or comp.get("skipped") or host in vm_hosts:
            continue
        b.blocking.append(f"image for host {host}: cannot be resolved to a deployable image — "
                          f"{comp.get('reason') or comp.get('image_hint') or 'unsupported component'}")


def _infrastructure(b: _Bundle) -> None:
    sid = b.scenario_id
    try:
        gen = generator.get_generated(sid)
    except FileNotFoundError:
        b.blocking.append("infrastructure/docker-compose.yml: not generated yet "
                          "(run IaC generation for this scenario before exporting)")
        return
    except generator.PlanError as exc:
        b.blocking.append(f"infrastructure/docker-compose.yml: generated file is stale or invalid "
                          f"and was not exported — {exc}")
        return

    compose = gen["compose"]
    try:
        parsed = yaml.safe_load(compose)
    except yaml.YAMLError as exc:  # generator guarantees valid YAML; fail closed anyway
        raise ExportError(f"generated compose is not valid YAML: {exc}") from exc
    services = (parsed or {}).get("services") or {}
    needs_template = any(isinstance(s.get("build"), dict) for s in services.values())
    if needs_template:
        if compose.count(_GEN_BUILD_CONTEXT) < 1:
            b.blocking.append("local build context: compose builds an image from an unrecognised context; "
                              "build context not bundled")
        elif not _TEMPLATE_DIR.is_dir():
            b.blocking.append(f"local build context {_TEMPLATE_DIR.name}: template directory missing "
                              "from this checkout")
        else:
            compose = compose.replace(_GEN_BUILD_CONTEXT, _BUNDLE_BUILD_CONTEXT)
            for item in sorted(_TEMPLATE_DIR.iterdir()):
                if item.is_file() and not item.is_symlink():
                    b.add(f"infrastructure/templates/demo-app/{item.name}", item.read_bytes(), GEN_TEMPLATE)
            b.notes.append("docker-compose.yml: the only change from the generator output is the local "
                           f"build context path (`{_GEN_BUILD_CONTEXT}` -> `{_BUNDLE_BUILD_CONTEXT}`) "
                           "so it resolves inside this bundle.")
    generated_by = GEN_IAC + (" (build context path relocated by app.poc.export)" if needs_template else "")
    b.add("infrastructure/docker-compose.yml", compose.encode("utf-8"), generated_by)
    b.add_json("infrastructure/iac-report.json", redact(gen["report"]), GEN_IAC)

    b.images = sorted({s["image"] for s in services.values() if s.get("image") and not s.get("build")})
    seen: dict[str, tuple[str, str, str]] = {}
    for name, op, arg in _ENV_REF_RE.findall(compose):
        if name not in seen:
            seen[name] = (name, op, arg)
    b.env_vars = list(seen.values())
    b.add("infrastructure/.env.example", _env_example(b.env_vars).encode("utf-8"), GEN_EXPORT)


def _env_example(env_vars: list[tuple[str, str, str]]) -> str:
    lines = [
        "# Placeholders for every ${VAR} read by docker-compose.yml. Copy to .env and fill in.",
        "# This file never contains a real secret. Generate fresh random values for secrets;",
        "# never reuse production credentials. Defaults shown are the generator's non-secret defaults.",
        "",
    ]
    if not env_vars:
        lines.append("# (docker-compose.yml reads no variables)")
    for name, op, arg in env_vars:
        secret = _is_secret_key(name)
        if secret or "?" in op:
            lines.append(f"# REQUIRED{' (sensitive value)' if secret else ''} - set at deploy time"
                         + (" — generate a fresh random value" if secret else ""))
            lines.append(f"{name}=")
        elif "-" in op:
            lines.append("# optional; default used when unset")
            lines.append(f"{name}={arg}")
        else:
            lines.append(f"{name}=")
    return "\n".join(lines) + "\n"


def _validation(b: _Bundle, ir: dict[str, Any], env_secrets: list[str]) -> list[dict[str, Any]]:
    sid = b.scenario_id
    plan = poc_store.get_plan(sid)
    if plan:
        b.add_json("validation/validation-plan.json", redact(plan, env_secrets), GEN_PLAN)
    else:
        b.notes.append("validation/validation-plan.json omitted: no ValidationPlan recorded (POST /api/poc/{id}/plan).")
    manifest = poc_store.get_manifest(sid)
    if manifest:
        b.add_json("validation/poc-manifest.json", redact(manifest, env_secrets), GEN_CANDIDATES)
    else:
        b.notes.append("validation/poc-manifest.json omitted: no PoC discovery recorded.")
    runs = redact(poc_store.get_runs(sid), env_secrets)
    chain = poc_store.get_chain(sid)
    if runs or chain:
        b.add_json("validation/results.json",
                   {"scenario_id": sid, "execution_results": runs,
                    "chain_validation": redact(chain, env_secrets) if chain else None},
                   GEN_RUNS)
    else:
        b.notes.append("validation/results.json omitted: no PoC execution or chain validation recorded.")
    # Export is read-only: never call service.report()/plan(), which re-generate and persist a plan.
    # The fidelity report is derived (pure functions of poc.chain) from the STORED plan + runs only.
    fidelity = None
    if not plan:
        b.notes.append("validation/fidelity-report.json omitted: no stored ValidationPlan to report against.")
    else:
        try:
            from app.poc import chain as chain_mod
            raw_runs = poc_store.get_runs(sid)
            chain_obj = chain_mod.validate_chain(sid, ir, plan, raw_runs)
            validation_report = None
            try:
                from app.validator import runner as v_runner
                validation_report = v_runner.get_latest_report(sid)
            except Exception:
                validation_report = None
            fidelity = chain_mod.build_fidelity_report(sid, ir, plan, raw_runs, chain_obj,
                                                       validation_report=validation_report)
        except ImportError:
            b.notes.append("validation/fidelity-report.json omitted: fidelity report not available in this build.")
        except Exception as exc:
            b.notes.append(f"validation/fidelity-report.json omitted: report unavailable ({type(exc).__name__}).")
    if fidelity:
        b.add_json("validation/fidelity-report.json", redact(fidelity, env_secrets), GEN_FIDELITY)
    return runs


def _evidence_index(b: _Bundle, runs: list[dict[str, Any]]) -> None:
    root = config.DATA_DIR.resolve()
    items = []
    for run in runs:
        for ev in run.get("evidence", []) or []:
            raw = str(ev.get("path") or "")
            entry = {"action_id": run.get("action_id"), "run_status": run.get("status"),
                     "kind": ev.get("kind"), "path": raw, "sha256": ev.get("sha256"),
                     "redacted": ev.get("redacted"), "note": ev.get("note"),
                     "present_on_exporting_host": False, "sha256_verified": False}
            try:
                p = Path(raw)
                p = (p if p.is_absolute() else root / p).resolve()
                inside = p == root or root in p.parents
                if raw and inside and p.is_file():
                    entry["present_on_exporting_host"] = True
                    h = hashlib.sha256()
                    with p.open("rb") as f:
                        for chunk in iter(lambda: f.read(1 << 20), b""):
                            h.update(chunk)
                    entry["sha256_verified"] = h.hexdigest() == ev.get("sha256")
            except OSError:
                pass
            items.append(entry)
    b.add_json("evidence/evidence-index.json", {
        "scenario_id": b.scenario_id,
        "raw_evidence_included": False,
        "note": ("Index only. Raw evidence stays under the exporting host's DATA_DIR and is not copied "
                 "into the bundle (it may contain target data). sha256_verified compares the stored file "
                 "with the hash recorded at execution time."),
        "items": items,
    }, GEN_EXPORT)



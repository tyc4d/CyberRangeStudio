"""Module 9 environment export: build a ZIP bundle from REAL project artifacts only.

Layout (owner prompt / CONTRACT §ExportManifest)::

    README.md
    manifest.json                      ExportManifest (per-file sha256; not listed in itself)
    scenario/scenario.json             Scenario IR (app.store.get), secret-redacted
    scenario/scenario.yaml             same IR as YAML
    scenario/attack-chain.json         IR actions + relations (+ flow when present)
    infrastructure/docker-compose.yml  iac.generator output (only if generated AND current)
    infrastructure/iac-report.json     iac.generator report for that compose
    infrastructure/templates/demo-app/ project build context, only when compose builds it
    infrastructure/.env.example        placeholders for every ${VAR} the compose reads
    validation/validation-plan.json    poc_plans row
    validation/poc-manifest.json       poc_candidates rows
    validation/results.json            poc_runs rows + latest poc_chains row
    validation/fidelity-report.json    poc.service.report(), only if it produces one
    evidence/evidence-index.json       index of run evidence (raw evidence is NOT copied)

Rules: nothing is fabricated. An artifact the project has not actually produced is omitted
(and, when it matters for rebuilding, listed in ``missing_for_rebuild``). Terraform/Ansible
are never generated by this project (the deploy runtime is Docker Compose + libvirt), so they
are omitted and listed as such. No real secret value is ever written: secret-looking fields
are redacted, ``.env.example`` holds placeholders only, and the finished bundle is scanned —
any hit aborts the export (fail closed).

Two export levels are reported separately (README + manifest):
  * descriptors exportable  — scenario/validation description files (always, if the scenario exists)
  * fully rebuildable       — ``manifest.rebuildable``: true only if nothing blocking is missing
"""

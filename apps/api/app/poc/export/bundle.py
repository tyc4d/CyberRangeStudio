def build_bundle(scenario_id: str) -> tuple[bytes, dict[str, Any]]:
    """Collect real artifacts and return (zip_bytes, manifest). Raises KeyError if unknown."""
    ir = store.get(scenario_id)
    if not isinstance(ir, dict):
        raise KeyError(scenario_id)
    env_secrets = _env_secret_values()
    b = _Bundle(scenario_id)

    _scenario(b, ir, env_secrets)
    _missing_hosts(b, _plan_report(ir, scenario_id))
    _infrastructure(b)
    runs = _validation(b, env_secrets)
    _evidence_index(b, runs)
    b.informational.extend(NOT_GENERATED_IAC)

    manifest: dict[str, Any] = {
        "scenario_id": scenario_id,
        "scenario_version": ir.get("ir_version", 1),
        "created_at": _now(),
        "files": [],
        "rebuildable": not b.blocking,
        "missing_for_rebuild": list(dict.fromkeys(b.blocking + b.informational)),
        "contains_secrets": False,
    }
    # TODO(Lead, integration): once the ExportManifest schema gains the optional
    # `export_levels` field (approved), set it here:
    #   manifest["export_levels"] = {"descriptors_exportable": True,   # scenario exists -> descriptors always exported
    #                                "fully_rebuildable": manifest["rebuildable"]}
    # Must be set before _validate_manifest() and before the README/file list is built.
    # README lists every other file, so build it against a provisional file list first.
    manifest["files"] = [{"path": p, "sha256": _sha256(d), "generated_by": g} for p, (d, g) in sorted(b.files.items())]
    b.add("README.md", _readme(b, ir, manifest).encode("utf-8"), GEN_EXPORT)
    manifest["files"] = [{"path": p, "sha256": _sha256(d), "generated_by": g} for p, (d, g) in sorted(b.files.items())]

    # Fail closed: nothing that looks like a secret may leave.
    for path, (data, _) in b.files.items():
        hits = find_secrets(data.decode("utf-8", errors="replace"), env_secrets)
        if hits:
            raise ExportError(f"refusing to export: {path} contains secret material ({', '.join(sorted(set(hits)))})")

    _validate_manifest(manifest)

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for path, (data, _) in sorted(b.files.items()):
            zf.writestr(zipfile.ZipInfo(path, date_time=(1980, 1, 1, 0, 0, 0)), data,
                        compress_type=zipfile.ZIP_DEFLATED)
        zf.writestr(zipfile.ZipInfo("manifest.json", date_time=(1980, 1, 1, 0, 0, 0)),
                    json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", compress_type=zipfile.ZIP_DEFLATED)
    return buf.getvalue(), manifest


def _validate_manifest(manifest: dict[str, Any]) -> None:
    try:
        from cr_contracts import iter_errors_shape
    except ImportError:  # contracts package without Module 9 shapes
        return
    errors = iter_errors_shape("ExportManifest", manifest)
    if errors:
        raise ExportError("manifest does not match the ExportManifest contract: " + "; ".join(errors))


def _output_path(scenario_id: str, version: Any) -> Path:
    generator.validate_id(scenario_id)  # also guarantees a safe path component
    out_dir = config.DATA_DIR / "exports" / scenario_id
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    base = f"{scenario_id}-v{version}-{stamp}"
    candidate, n = out_dir / f"{base}.zip", 1
    while candidate.exists():  # never overwrite an earlier export
        n += 1
        candidate = out_dir / f"{base}-{n}.zip"
    return candidate


def export(scenario_id: str) -> dict[str, Any]:
    """Build, write and record the bundle. Returns ``{bundle_path, manifest}`` (CONTRACT §HTTP API)."""
    data, manifest = build_bundle(scenario_id)
    path = _output_path(scenario_id, manifest["scenario_version"])
    tmp = path.with_suffix(".zip.partial")
    with open(tmp, "xb") as f:
        f.write(data)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)
    poc_store.save_export(scenario_id, str(path), manifest)
    return {"bundle_path": str(path), "manifest": manifest}


def verify_bundle(path_or_bytes: str | Path | bytes) -> list[str]:
    """Re-check a bundle: every listed sha256 matches, nothing unlisted, no secrets. [] = OK."""
    src = io.BytesIO(path_or_bytes) if isinstance(path_or_bytes, bytes) else path_or_bytes
    errors: list[str] = []
    with zipfile.ZipFile(src) as zf:
        names = set(zf.namelist())
        if "manifest.json" not in names:
            return ["manifest.json missing"]
        manifest = json.loads(zf.read("manifest.json"))
        listed = {f["path"] for f in manifest.get("files", [])}
        for f in manifest.get("files", []):
            if f["path"] not in names:
                errors.append(f"listed but absent: {f['path']}")
                continue
            data = zf.read(f["path"])
            if _sha256(data) != f["sha256"]:
                errors.append(f"sha256 mismatch: {f['path']}")
            if find_secrets(data.decode("utf-8", errors="replace")):
                errors.append(f"secret material in {f['path']}")
        for extra in sorted(names - listed - {"manifest.json"}):
            errors.append(f"unlisted file in bundle: {extra}")
        if manifest.get("contains_secrets") is not False:
            errors.append("contains_secrets must be false")
        if manifest.get("rebuildable") and any(
                not m.startswith(("infrastructure/terraform/", "infrastructure/ansible/"))
                for m in manifest.get("missing_for_rebuild", [])):
            errors.append("rebuildable=true while blocking items are missing")
    return errors

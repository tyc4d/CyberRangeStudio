# --- secret handling ---------------------------------------------------------
# STRUCTURAL redaction. A value is treated as a secret because of the structure around it — a
# secret-named key or label (bare, quoted or escaped), an Authorization/Cookie header, URL userinfo
# (with or without scheme), a secret-named (percent-decoded) query parameter, or a secret-named
# ${VAR} branch — never because of how the value looks. The value extent is parsed structurally:
# every concatenated quoted/bare/${...} segment, so quoting, escaping or concatenation cannot hide
# part of it. Embedded JSON/YAML is resolved BEFORE redaction and re-serialized from the cleaned
# object. Both the emitted files and embedded documents are parsed again by the final scan;
# ambiguous/malformed structures are unsafe, never evidence that a value was removed.
_SECRET_KEY_RE = re.compile(
    r"(?:^|[_\-.])(password|passwd|pwd|passphrase|secret|secrets|token|tokens|api[_-]?key|apikey|"
    r"access[_-]?key|secret[_-]?key|private[_-]?key|client[_-]?secret|cookie|cookies|set[_-]?cookie|"
    r"credential|credentials|auth[_-]?token|bearer|authorization|session[_-]?id|sessionid)(?:$|[_\-.])",
    re.IGNORECASE,
)
# High-confidence secret material: always redacted from text and fatal if found at the end.
_SECRET_VALUE_PATTERNS = (
    re.compile(r"-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----[\s\S]*?(?:-----END [A-Z0-9 ]*PRIVATE KEY-----|$)"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"\bgh[pousr]_[A-Za-z0-9]{36,}\b"),
    re.compile(r"\bgithub_pat_[A-Za-z0-9_]{40,}\b"),
    re.compile(r"\bsk-(?:ant-|proj-)?[A-Za-z0-9_-]{20,}\b"),
    re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b"),
    re.compile(r"(?i)\bbearer\s+(?!\[REDACTED\])[A-Za-z0-9._~+/-]{16,}=*"),
    re.compile(r"PVEAPIToken=[^\s'\"]+"),
)
# Secret label in free text: optional (escaped) quote, label, optional quote, then ':' or '='.
_LABEL_WORDS = (r"password|passwd|pwd|passphrase|secret|token|api[_\-]?key|apikey|access[_\-]?key|"
                r"private[_\-]?key|credential|session[_\-]?id|sessionid|cookie|authorization")
_LABEL_RE = re.compile(
    r"(?i)(?<![A-Za-z0-9_.\-])(?<!\$\{)(\\*[\"']?)([A-Za-z0-9_.\-]*?(?:" + _LABEL_WORDS + r")[A-Za-z0-9_\-]*)"
    r"(\\*[\"']?)([ \t]*[:=][ \t]*)")
_HEADER_LABELS = {"authorization", "proxy-authorization", "cookie", "set-cookie"}
_QUOTE_RE = re.compile(r"\\*[\"']")
_BARE_STOP = set(" \t\r\n,;&<>")
_NULLISH = {"true", "false", "null", "none"}
# URL userinfo, with or without scheme: everything after '//' up to the LAST '@' of the authority.
_URL_USERINFO_RE = re.compile(r"(?i)((?:\b[a-z][a-z0-9+.\-]*:)?//)([^\s/?#<>\\]*)@")
# Query / fragment parameters; the NAME is fully percent-decoded before classification.
_QUERY_PARAM_RE = re.compile(r"([?&#;])([^=&#\s\"'<>?;]+)=([^&#\s<>]*)")
_QUERY_SECRET_NAME_RE = re.compile(
    r"token|secret|pass|pwd|api[_\-]?key|apikey|access[_\-]?key|auth|sig|session|credential|cookie|key",
    re.IGNORECASE)
_REF_HEAD_RE = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)(:?[-?+=])?", re.S)
_SAFE_SECRET_REF_RE = re.compile(r"(?:\$\{[A-Za-z_][A-Za-z0-9_]*(?::?[-?+=](?:\[REDACTED\])?)?\})+")
_SECRET_VAR_NAME_RE = re.compile(r"PASS|PWD|SECRET|TOKEN|API_?KEY|ACCESS_?KEY|PRIVATE_?KEY|CREDENTIAL|COOKIE",
                                 re.IGNORECASE)
_ENV_REF_RE = re.compile(r"\$\{([A-Z][A-Z0-9_]*)(?:(:?[-?])([^}]*))?\}")


class ExportError(RuntimeError):
    """The bundle cannot be produced safely (e.g. a secret would be written)."""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _decode_name(name: str) -> str:
    for _ in range(4):
        decoded = unquote(name)
        if decoded == name:
            break
        name = decoded
    return name


def _is_secret_key(key: Any) -> bool:
    """Secret-named field? Fully percent-decoded and camelCase-split before matching."""
    if isinstance(key, bytes):
        try:
            key = key.decode("utf-8")
        except UnicodeDecodeError:
            return False
    if not isinstance(key, str):
        return False
    decoded = _decode_name(key)
    snake = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", decoded)
    return bool(_SECRET_KEY_RE.search(decoded) or _SECRET_KEY_RE.search(snake))


def _env_secret_values() -> list[str]:
    """Literal values of secret-looking variables in the API process environment."""
    values = {config.OPENAI_API_KEY} if getattr(config, "OPENAI_API_KEY", "") else set()
    for key, value in os.environ.items():
        if value and _is_secret_key(key):
            values.add(value)
    # Short values (e.g. "1", "true") would match everywhere and are not credentials.
    return sorted((v for v in values if len(v) >= 8), key=len, reverse=True)


def _matching_brace(text: str, open_idx: int) -> Optional[int]:
    depth = 0
    for i in range(open_idx, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return i
    return None


def _walk_refs(text: str, force: bool = False) -> str:
    """Rewrite ${...} interpolations (nesting-aware).

    force=True (inside a secret-named field): every branch argument becomes [REDACTED]. Otherwise
    the branches of secret-named variables are redacted, and arguments of other refs are walked
    recursively so a nested secret-named ref is still caught.
    """
    out: list[str] = []
    i = 0
    while True:
        j = text.find("${", i)
        if j < 0:
            out.append(text[i:])
            break
        out.append(text[i:j])
        k = _matching_brace(text, j + 1)
        if k is None:  # unbalanced: nothing structured left to keep
            out.append(REDACTED if force else text[j:])
            break
        inner = text[j + 2:k]
        m = _REF_HEAD_RE.match(inner)
        if not m:
            out.append("${" + _walk_refs(inner, force) + "}")
        else:
            name, op = m.group(1), m.group(2) or ""
            arg = inner[m.end():]
            if arg and arg != REDACTED and (force or (op and _SECRET_VAR_NAME_RE.search(name))):
                arg = REDACTED
            elif arg:
                arg = _walk_refs(arg, force)
            out.append("${" + name + op + arg + "}")
        i = k + 1
    return "".join(out)


_BLOCK_INDICATOR_RE = re.compile(r"[|>][+-]?[0-9]?[+-]?(?:[ \t]+#.*)?")


def _line_end(text: str, pos: int) -> int:
    nl = text.find("\n", pos)
    return len(text) if nl < 0 else nl


def _indent_of_line(text: str, pos: int) -> int:
    start = text.rfind("\n", 0, pos) + 1
    line = text[start:_line_end(text, start)]
    return len(line) - len(line.lstrip(" \t"))


def _continuation_end(text: str, eol: int, indent: int) -> int:
    """Extend over following lines that are blank or indented deeper than ``indent`` (YAML block /
    plain multi-line scalar / folded header). Returns the new end offset."""
    n = len(text)
    j = eol
    while j < n and text[j] == "\n":
        nxt = _line_end(text, j + 1)
        line = text[j + 1:nxt]
        if line.strip() and len(line) - len(line.lstrip(" \t")) <= indent:
            break
        if not line.strip() and nxt >= n:
            break  # do not swallow the final newline
        j = nxt
    # trailing blank lines are not part of the value
    while j > eol and text[j - 1:j] == "\n":
        j -= 1
    return j


def _value_end(text: str, start: int, header: bool, indent: int = 0) -> int:
    """End of the value that follows a secret label — across lines where the structure says so.

    Covers ALL adjacent quoted / ${...} / bare segments; quoted segments may span lines; a shell
    backslash-newline continues the value; an empty rest-of-line or a YAML block indicator (| >)
    takes every following line indented deeper than the label; a value ending at end-of-line is
    extended over deeper-indented continuation lines (YAML plain multi-line). Headers run to the end
    of the line plus folded continuation lines.
    """
    n = len(text)
    eol = _line_end(text, start)
    rest = text[start:eol].strip()
    if header:
        return _continuation_end(text, eol, indent)
    if rest == "" or _BLOCK_INDICATOR_RE.fullmatch(rest):
        return _continuation_end(text, eol, indent)
    j = start
    after_quote = False
    while j < n:
        q = _QUOTE_RE.match(text, j)
        if q:
            close = text.find(q.group(0), q.end())
            if close < 0:  # unterminated quote: everything after it is the value
                return n
            j = close + len(q.group(0))
            after_quote = True
            continue
        if text.startswith("${", j):
            k = _matching_brace(text, j + 1)
            if k is None:
                return n
            j = k + 1
            continue
        if text[j] == "\\" and text[j + 1:j + 2] == "\n":  # shell line continuation
            j += 2
            continue
        if text[j] == "\\" and text[j + 1:j + 3] == "\r\n":
            j += 3
            continue
        if text[j] in _BARE_STOP or (after_quote and text[j] in "}])"):
            break  # a closing bracket right after a quoted value closes the enclosing structure
        j += 1
    if text[j:_line_end(text, j)].strip() == "":
        j = max(j, _continuation_end(text, _line_end(text, j), indent))
    return j


def _value_safe(value: str, compose: bool = False) -> bool:
    """A labelled value is safe only if it is WHOLLY empty / [REDACTED] / nullish / bare refs."""
    s = value.strip()
    while True:
        m = re.fullmatch(r"(\\*[\"'])(.*)\1", s, re.S)
        if not m:
            break
        s = m.group(2)
    if s in ("", REDACTED) or s.lower() in _NULLISH or _SAFE_SECRET_REF_RE.fullmatch(s):
        return True
    # The generator's own deploy-time refs (e.g. ${CR_DB_PASSWORD:?set at deploy time}) in its compose.
    return compose and bool(generator._RUNTIME_REF_RE.fullmatch(s))


def _label_pass(text: str, fix: bool, compose: bool = False) -> tuple[str, bool]:
    """Find secret-labelled values; with fix=True replace each unsafe value whole."""
    out: list[str] = []
    pos = 0
    found = False
    search_from = 0
    while True:
        m = _LABEL_RE.search(text, search_from)
        if not m:
            break
        label = m.group(2).lower()
        header = label in _HEADER_LABELS
        vstart = m.end()
        vend = _value_end(text, vstart, header, _indent_of_line(text, m.start()))
        value = text[vstart:vend]
        if not _value_safe(value, compose):
            found = True
            if fix:
                q = _QUOTE_RE.match(value)
                quote = q.group(0) if q and not header else ""
                out.append(text[pos:vstart] + quote + REDACTED + quote)
                pos = vend
        search_from = max(vend, m.end(), search_from + 1)
    out.append(text[pos:])
    return ("".join(out) if fix else text), found


def _unsafe_userinfo(m: re.Match) -> bool:
    return m.group(2) not in ("", REDACTED)


def _unsafe_query(m: re.Match) -> bool:
    value = m.group(3)
    return value not in ("", REDACTED) and bool(_QUERY_SECRET_NAME_RE.search(_decode_name(m.group(2))))


def _secret_ref_branch(text: str) -> bool:
    for m in re.finditer(r"\$\{([A-Za-z_][A-Za-z0-9_]*)(:?[-+=])", text):
        if _SECRET_VAR_NAME_RE.search(m.group(1)):
            k = _matching_brace(text, m.start() + 1)
            arg = text[m.end():k] if k is not None else text[m.end():]
            if arg and arg != REDACTED:
                return True
    return False


def redact_text(text: str, env_secrets: list[str] | None = None) -> str:
    for secret in env_secrets if env_secrets is not None else _env_secret_values():
        text = text.replace(secret, REDACTED)
    for pattern in _SECRET_VALUE_PATTERNS:
        text = pattern.sub(REDACTED, text)
    text = _URL_USERINFO_RE.sub(lambda m: m.group(1) + REDACTED + "@" if _unsafe_userinfo(m) else m.group(0), text)
    text = _QUERY_PARAM_RE.sub(
        lambda m: m.group(1) + m.group(2) + "=" + REDACTED if _unsafe_query(m) else m.group(0), text)
    text = _walk_refs(text)
    text, _ = _label_pass(text, fix=True)
    return text


def _redact_secret_field(value: str) -> str:
    """A string inside a secret-named field: keep only bare interpolation structure, else redact."""
    if not value or value == REDACTED:
        return value
    rewritten = _walk_refs(value, force=True)
    return rewritten if _SAFE_SECRET_REF_RE.fullmatch(rewritten) else REDACTED


_MAX_STRUCTURE_DEPTH = 64
_YAML_KEY_LINE_RE = re.compile(
    r"(?m)^[ \t]*(?:-[ \t]+)?(?:[^\s{}\[\],:#&*!|>'\"%@`]+|"
    r"\"(?:\\.|[^\"\\])*\"|'(?:[^']|'')*')[ \t]*:(?=\s|$|[\[\]{},])")


@dataclass(frozen=True)
class _Embedded:
    value: Any
    format: str
    prefix: str = ""


def _structure_candidate(text: str) -> bool:
    s = text.lstrip()
    return bool(s and (s[0] in "{[\"'!&*|>" or s.startswith(("---", "%YAML", "%TAG", "? ", "- "))
                       or _YAML_KEY_LINE_RE.search(text)))


def _parse_embedded(text: str) -> _Embedded | None:
    """Resolve embedded documents, distinguish prose from an UNPARSABLE document.

    A prose introduction followed by a YAML document is supported by parsing the entire suffix;
    its prefix is checked separately. No secret-value extent is inferred from text offsets.
    Unknown tags, malformed flow/block values and incomplete documents must fail closed. Scalar
    quotes/tags are also resolved, so an encoded string containing another document is walked.
    """
    s = text.strip()
    if not s or s == REDACTED or _SAFE_SECRET_REF_RE.fullmatch(s):
        return None
    if not any(c in text for c in ":\n{[\"'!&*|>%"):
        return None
    if s[0] in '{["':
        try:
            return _Embedded(json.loads(s), "json")
        except (ValueError, RecursionError):
            pass  # A YAML flow collection or quoted scalar can still be valid.
    try:
        obj = yaml.safe_load(text)
    except (yaml.YAMLError, ValueError, RecursionError):
        # Preserve ordinary introductions, but require a complete parse of the following YAML.
        for match in re.finditer(r"\n(?=\S)", text):
            suffix = text[match.end():]
            if not _structure_candidate(suffix):
                continue
            try:
                obj = yaml.safe_load(suffix)
            except (yaml.YAMLError, ValueError, RecursionError):
                continue
            if isinstance(obj, (dict, list)):
                return _Embedded(obj, "yaml", text[:match.end()])
        if _structure_candidate(text):
            raise ExportError("cannot parse embedded JSON/YAML to confirm it is secret-free") from None
        return None  # Unstructured prose still receives the label/header/URL scan.
    if isinstance(obj, (dict, list, tuple, set, bytes)) or s[0] in "\"'!&|>" or s.startswith("---"):
        return _Embedded(obj, "yaml")
    return None


def _embedded_structure(text: str) -> Any:
    """Compatibility helper: a parsed structure (including prose prefix), or known prose only.

    A parse failure for a document candidate raises ExportError; it must never become None.
    """
    if not isinstance(text, str):
        return None
    parsed = _parse_embedded(text)
    if parsed is None:
        return None
    return [parsed.prefix, parsed.value] if parsed.prefix else parsed.value


def _redact_free_string(value: str, env_secrets: list[str], depth: int = 0) -> str:
    embedded = _parse_embedded(value)
    if embedded is not None:
        obj = redact(embedded.value, env_secrets, _depth=depth + 1)
        try:
            body = (json.dumps(obj, ensure_ascii=False) if embedded.format == "json" or isinstance(obj, str)
                    else yaml.safe_dump(obj, allow_unicode=True, sort_keys=False))
        except (TypeError, ValueError, yaml.YAMLError, RecursionError):
            raise ExportError("cannot serialize cleaned embedded JSON/YAML safely") from None
        prefix = _redact_free_string(embedded.prefix, env_secrets, depth + 1) if embedded.prefix else ""
        cleaned = prefix + body
        # Reparse exactly what will be written, including every resolved YAML tag/alias/scalar.
        resolved = _embedded_structure(cleaned)
        if resolved is None or find_field_secrets(resolved, _depth=depth + 1) \
                or find_secrets(cleaned, env_secrets, structural=False):
            raise ExportError("cannot prove cleaned embedded JSON/YAML is secret-free")
    else:
        cleaned = redact_text(value, env_secrets)
        if find_secrets(cleaned, env_secrets) or find_field_secrets({"text": cleaned}, _depth=depth + 1):
            raise ExportError("cannot prove cleaned text is secret-free")
    return cleaned


# Mapping keys allowed to stay as-is INSIDE a secret-named subtree (field names, not data).
_BENIGN_SECRET_SUBKEYS = frozenset({
    "id", "name", "type", "kind", "username", "user", "user_name", "login", "account", "password", "passwd",
    "pwd", "passphrase", "secret", "token", "value", "key", "api_key", "apikey", "access_key", "secret_key",
    "private_key", "client_id", "client_secret", "note", "notes", "description", "source", "host", "port",
    "service", "scope", "expires", "expires_at", "created_at", "issuer", "hash", "algorithm", "format", "redacted",
})
_REDACTED_KEY_RE = re.compile(r"\[REDACTED-key-\d+(?:-\d+)?\]")


def _key_allowed_under_secret(key: Any) -> bool:
    return isinstance(key, str) and (key.lower() in _BENIGN_SECRET_SUBKEYS or bool(_REDACTED_KEY_RE.fullmatch(key)))


def _scalar_leaves(obj: Any, under_secret: bool = False, *, depth: int = 0,
                   active: frozenset[int] = frozenset()):
    """Walk resolved values AND data keys, retaining their secret-subtree context.

    This also lets us prove a known secret wasn't retained through a public YAML alias/copy.
    Field names themselves are not secret data merely because they label a secret subtree.
    """
    if depth > _MAX_STRUCTURE_DEPTH:
        raise ExportError("structure too deep to confirm it is secret-free")
    if isinstance(obj, (dict, list)):
        if id(obj) in active:
            raise ExportError("cyclic structure cannot be confirmed secret-free")
        active = active | {id(obj)}
        if isinstance(obj, dict):
            for key, value in obj.items():
                yield from _scalar_leaves(key, under_secret and not _key_allowed_under_secret(key),
                                          depth=depth + 1, active=active)
                yield from _scalar_leaves(value, under_secret or _is_secret_key(key),
                                          depth=depth + 1, active=active)
        else:
            for value in obj:
                yield from _scalar_leaves(value, under_secret, depth=depth + 1, active=active)
    elif isinstance(obj, (str, bytes)) and obj:
        yield obj, under_secret


def redact(obj: Any, env_secrets: list[str] | None = None, _under_secret: bool = False,
           *, _depth: int = 0, _active: frozenset[int] = frozenset()) -> Any:
    """Redact a resolved object, and refuse if any known secret literal is still retained.

    Aliases may expose the same scalar under both password and an otherwise public field/key.
    Merely cleaning the password field is insufficient; refuse an ambiguous remaining copy.
    """
    known = {value for value, secret in _scalar_leaves(obj, _under_secret) if secret
             and (not isinstance(value, str) or (value != REDACTED and not _SAFE_SECRET_REF_RE.fullmatch(value)))}
    cleaned = _redact_value(obj, env_secrets, _under_secret, _depth=_depth, _active=_active)
    if known:
        for value, _ in _scalar_leaves(cleaned):
            if isinstance(value, str) and (value == REDACTED or _SAFE_SECRET_REF_RE.fullmatch(value)):
                continue
            if any(type(value) is type(secret) and (value == secret or (len(secret) >= 8 and secret in value))
                   for secret in known):
                raise ExportError("cannot prove all copies of a secret-named value were removed")
    return cleaned


def _redact_value(obj: Any, env_secrets: list[str] | None = None, _under_secret: bool = False,
                  *, _depth: int = 0, _active: frozenset[int] = frozenset()) -> Any:
    """Deep copy with secret-named fields, secret-structured text AND mapping keys redacted.

    Inside a secret-named subtree a key is kept only if it is a known field name; any other key
    (which may itself be the credential) becomes ``[REDACTED-key-<n>]``. A string that is itself
    JSON/YAML is parsed and redacted structurally. Cycles, unsupported collections and excessive
    nesting are refused rather than skipped, including those introduced by YAML aliases/tags.
    """
    if _depth > _MAX_STRUCTURE_DEPTH:
        raise ExportError("structure too deep to confirm it is secret-free")
    if isinstance(obj, (dict, list)):
        if id(obj) in _active:
            raise ExportError("cyclic structure cannot be confirmed secret-free")
        _active = _active | {id(obj)}
    env_secrets = _env_secret_values() if env_secrets is None else env_secrets
    if isinstance(obj, dict):
        out: dict[Any, Any] = {}
        for n, (key, value) in enumerate(obj.items(), 1):
            secret_key = _is_secret_key(key)
            if isinstance(key, str):
                if _under_secret and not _key_allowed_under_secret(key):
                    new_key = f"[REDACTED-key-{n}]"
                else:
                    new_key = _redact_free_string(key, env_secrets, _depth)
            else:
                new_key = REDACTED if _under_secret else key
            while new_key in out:
                new_key = f"[REDACTED-key-{n}-{len(out)}]"
            out[new_key] = _redact_value(value, env_secrets, _under_secret or secret_key,
                                         _depth=_depth + 1, _active=_active)
        return out
    if isinstance(obj, list):
        return [_redact_value(v, env_secrets, _under_secret, _depth=_depth + 1, _active=_active) for v in obj]
    if isinstance(obj, str):
        return _redact_secret_field(obj) if _under_secret else _redact_free_string(obj, env_secrets, _depth)
    if _under_secret and obj is not None and not isinstance(obj, bool):
        return REDACTED
    if isinstance(obj, (tuple, set)):
        raise ExportError("unsupported YAML collection cannot be confirmed secret-free")
    return obj


def find_secrets(text: str, env_secrets: list[str] | None = None, *, structural: bool = True,
                 compose: bool = False) -> list[str]:
    """Names of secret indicators present in ``text`` (empty = clean). Never returns the value.

    structural=False limits the check to literal env secrets + high-confidence value patterns
    (used on the escaped text of JSON/YAML files, whose decoded strings are checked structurally).
    compose=True allows the generator's own ${CR_...:?msg} deploy-time refs as labelled values.
    """
    hits = []
    for secret in env_secrets if env_secrets is not None else _env_secret_values():
        if secret in text:
            hits.append("process-environment secret value")
    for pattern in _SECRET_VALUE_PATTERNS:
        if pattern.search(text):
            hits.append(f"pattern {pattern.pattern[:32]}")
    if not structural:
        return hits
    if any(_unsafe_userinfo(m) for m in _URL_USERINFO_RE.finditer(text)):
        hits.append("credentials in URL userinfo")
    if any(_unsafe_query(m) for m in _QUERY_PARAM_RE.finditer(text)):
        hits.append("secret-named URL query parameter")
    if _secret_ref_branch(text):
        hits.append("literal value branch of a secret-named ${VAR...} reference")
    if _label_pass(text, fix=False, compose=compose)[1]:
        hits.append("secret label/header with an unredacted value")
    return hits


def find_field_secrets(obj: Any, _under_secret: bool = False, _path: str = "",
                       *, _depth: int = 0, _active: frozenset[int] = frozenset()) -> list[str]:
    """Field-aware check of parsed JSON/YAML (fail closed).

    Under a secret-named key only empty / null / bool / [REDACTED] / bare redacted refs are allowed,
    and only known field names as mapping keys. Every other string (and key) is checked with the
    structural text scan; embedded JSON/YAML is resolved and checked recursively. Failure to
    resolve a document is a hit, including when a prior text redactor left a safe-looking label.
    """
    if _depth > _MAX_STRUCTURE_DEPTH:
        return ["structure too deep to confirm it is secret-free"]
    if isinstance(obj, (dict, list)):
        if id(obj) in _active:
            return ["cyclic structure cannot be confirmed secret-free"]
        _active = _active | {id(obj)}
    hits: list[str] = []
    if isinstance(obj, dict):
        for n, (key, value) in enumerate(obj.items()):
            if _under_secret and not _key_allowed_under_secret(key):
                hits.append(f"unredacted mapping key in secret-named field {_path}/#{n}")
            elif isinstance(key, str):
                hits += find_field_secrets(key, _path=f"{_path}/key#{n}",
                                           _depth=_depth + 1, _active=_active)
            shown = (isinstance(key, str) and re.fullmatch(r"[A-Za-z0-9_\-]{1,32}", key) is not None
                     and (_key_allowed_under_secret(key) or not _under_secret) and not find_secrets(key, []))
            hits += find_field_secrets(value, _under_secret or _is_secret_key(key),
                                       f"{_path}/{key if shown else '#' + str(n)}",
                                       _depth=_depth + 1, _active=_active)
    elif isinstance(obj, list):
        if _under_secret and obj == ["REDACTED"]:
            return hits  # how YAML parses an unquoted `key: [REDACTED]` marker in free text
        for n, value in enumerate(obj):
            hits += find_field_secrets(value, _under_secret, f"{_path}/{n}",
                                       _depth=_depth + 1, _active=_active)
    elif _under_secret:
        if isinstance(obj, str):
            if obj and obj != REDACTED and not _SAFE_SECRET_REF_RE.fullmatch(obj):
                hits.append(f"unredacted value in secret-named field {_path}")
        elif obj is not None and not isinstance(obj, bool) and obj != b"":
            hits.append(f"unredacted value in secret-named field {_path}")
    elif isinstance(obj, str):
        try:
            embedded = _embedded_structure(obj)
        except ExportError:
            return [f"cannot parse embedded JSON/YAML in {_path}"]
        if embedded is not None:
            hits += find_field_secrets(embedded, False, f"{_path}(embedded)",
                                       _depth=_depth + 1, _active=_active)
        elif find_secrets(obj, []):
            hits.append(f"secret-structured text in {_path}")
    elif isinstance(obj, (tuple, set)):
        hits.append(f"unsupported YAML collection in {_path}")
    return hits


_COMPOSE_PATH = "infrastructure/docker-compose.yml"


def _file_secrets(path: str, data: bytes, env_secrets: list[str] | None = None) -> list[str]:
    """Final per-file scan used by build_bundle AND verify_bundle.

    JSON/YAML (except the generator compose): parsed and checked field-by-field on decoded strings,
    plus literal/pattern checks on the raw text; unparsable => refused. Other files: full
    structural text scan (the compose may hold only the generator's own deploy-time refs).
    """
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return [f"cannot decode {path} to confirm it is secret-free"]
    if path != _COMPOSE_PATH and path.endswith((".json", ".yaml", ".yml")):
        try:
            obj = json.loads(text) if path.endswith(".json") else yaml.safe_load(text)
        except (ValueError, yaml.YAMLError, RecursionError):
            return [f"cannot parse {path} to confirm it is secret-free"]
        return find_secrets(text, env_secrets, structural=False) + find_field_secrets(obj)
    return find_secrets(text, env_secrets, compose=(path == _COMPOSE_PATH))


# --- collection ---------------------------------------------------------------
class _Bundle:
    def __init__(self, scenario_id: str):
        self.scenario_id = scenario_id
        self.files: dict[str, tuple[bytes, str]] = {}
        self.blocking: list[str] = []      # missing items that prevent a full rebuild
        self.informational: list[str] = []  # listed in missing_for_rebuild, not blocking
        self.notes: list[str] = []          # README-only remarks (omitted descriptors etc.)
        self.images: list[str] = []
        self.env_vars: list[tuple[str, str, str]] = []

    def add_json(self, path: str, obj: Any, generated_by: str) -> None:
        self.add(path, (json.dumps(obj, ensure_ascii=False, indent=2, sort_keys=False) + "\n").encode("utf-8"),
                 generated_by)

    def add(self, path: str, data: bytes, generated_by: str) -> None:
        if path in self.files or path == "manifest.json":
            raise ExportError(f"duplicate bundle path {path}")
        self.files[path] = (data, generated_by)


def _scenario(b: _Bundle, ir: dict[str, Any], env_secrets: list[str]) -> None:
    safe_ir = redact(ir, env_secrets)
    b.add_json("scenario/scenario.json", safe_ir, GEN_IR)
    b.add("scenario/scenario.yaml",
          yaml.safe_dump(safe_ir, sort_keys=False, allow_unicode=True).encode("utf-8"), GEN_IR)
    chain = {"scenario_id": b.scenario_id,
             "source": "Scenario IR actions + relations (the described attack chain, not a validation result)",
             "actions": safe_ir.get("actions", []) or [],
             "relations": safe_ir.get("relations", []) or []}
    if safe_ir.get("flow") is not None:
        chain["flow"] = safe_ir["flow"]
    b.add_json("scenario/attack-chain.json", chain, GEN_IR)


def _plan_report(ir: dict[str, Any], scenario_id: str) -> Optional[dict[str, Any]]:
    plan = ir.get("environment_plan")
    if not plan:
        return None
    try:
        _, report = generator.inspect_plan(plan, scenario_id)
        return report
    except Exception:  # an invalid plan simply yields no report
        return None


def _missing_hosts(b: _Bundle, report: Optional[dict[str, Any]]) -> None:
    if report is None:
        b.blocking.append("environment plan: the scenario has no valid environment plan (module 5), "
                          "so no deployable environment exists to export")
        return
    vm_hosts = set()
    for vm in report.get("vms", []) or []:
        host = vm.get("host_id")
        vm_hosts.add(host)
        b.blocking.append(f"VM image for host {host} (runtime=vm): not exportable/not bundled — "
                          f"{vm.get('reason') or 'VM guest image must be supplied separately'}")
    for nd in report.get("not_deployed_hosts", []) or []:
        b.blocking.append(f"image for host {nd.get('host_id')}: none available, host is not deployed — "
                          f"{nd.get('reason')}")
    for comp in report.get("components", []) or []:
        host = comp.get("host_id")
        if comp.get("deployable", True) or comp.get("skipped") or host in vm_hosts:
            continue
        b.blocking.append(f"image for host {host}: cannot be resolved to a deployable image — "
                          f"{comp.get('reason') or comp.get('image_hint') or 'unsupported component'}")


def _infrastructure(b: _Bundle) -> None:
    sid = b.scenario_id
    try:
        gen = generator.get_generated(sid)
    except FileNotFoundError:
        b.blocking.append("infrastructure/docker-compose.yml: not generated yet "
                          "(run IaC generation for this scenario before exporting)")
        return
    except generator.PlanError as exc:
        b.blocking.append(f"infrastructure/docker-compose.yml: generated file is stale or invalid "
                          f"and was not exported — {exc}")
        return

    compose = gen["compose"]
    try:
        parsed = yaml.safe_load(compose)
    except yaml.YAMLError as exc:  # generator guarantees valid YAML; fail closed anyway
        raise ExportError(f"generated compose is not valid YAML: {exc}") from exc
    services = (parsed or {}).get("services") or {}
    needs_template = any(isinstance(s.get("build"), dict) for s in services.values())
    if needs_template:
        if compose.count(_GEN_BUILD_CONTEXT) < 1:
            b.blocking.append("local build context: compose builds an image from an unrecognised context; "
                              "build context not bundled")
        elif not _TEMPLATE_DIR.is_dir():
            b.blocking.append(f"local build context {_TEMPLATE_DIR.name}: template directory missing "
                              "from this checkout")
        else:
            compose = compose.replace(_GEN_BUILD_CONTEXT, _BUNDLE_BUILD_CONTEXT)
            for item in sorted(_TEMPLATE_DIR.iterdir()):
                if item.is_file() and not item.is_symlink():
                    b.add(f"infrastructure/templates/demo-app/{item.name}", item.read_bytes(), GEN_TEMPLATE)
            b.notes.append("docker-compose.yml: the only change from the generator output is the local "
                           f"build context path (`{_GEN_BUILD_CONTEXT}` -> `{_BUNDLE_BUILD_CONTEXT}`) "
                           "so it resolves inside this bundle.")
    generated_by = GEN_IAC + (" (build context path relocated by app.poc.export)" if needs_template else "")
    b.add("infrastructure/docker-compose.yml", compose.encode("utf-8"), generated_by)
    b.add_json("infrastructure/iac-report.json", redact(gen["report"]), GEN_IAC)

    b.images = sorted({s["image"] for s in services.values() if s.get("image") and not s.get("build")})
    seen: dict[str, tuple[str, str, str]] = {}
    for name, op, arg in _ENV_REF_RE.findall(compose):
        if name not in seen:
            seen[name] = (name, op, arg)
    b.env_vars = list(seen.values())
    b.add("infrastructure/.env.example", _env_example(b.env_vars).encode("utf-8"), GEN_EXPORT)


def _env_example(env_vars: list[tuple[str, str, str]]) -> str:
    lines = [
        "# Placeholders for every ${VAR} read by docker-compose.yml. Copy to .env and fill in.",
        "# This file never contains a real secret. Generate fresh random values for secrets;",
        "# never reuse production credentials. Defaults shown are the generator's non-secret defaults.",
        "",
    ]
    if not env_vars:
        lines.append("# (docker-compose.yml reads no variables)")
    for name, op, arg in env_vars:
        secret = _is_secret_key(name)
        if secret or "?" in op:
            lines.append(f"# REQUIRED{' (sensitive value)' if secret else ''} - set at deploy time"
                         + (" — generate a fresh random value" if secret else ""))
            lines.append(f"{name}=")
        elif "-" in op:
            lines.append("# optional; default used when unset")
            lines.append(f"{name}={arg}")
        else:
            lines.append(f"{name}=")
    return "\n".join(lines) + "\n"


def _validation(b: _Bundle, ir: dict[str, Any], env_secrets: list[str]) -> list[dict[str, Any]]:
    sid = b.scenario_id
    plan = poc_store.get_plan(sid)
    if plan:
        b.add_json("validation/validation-plan.json", redact(plan, env_secrets), GEN_PLAN)
    else:
        b.notes.append("validation/validation-plan.json omitted: no ValidationPlan recorded (POST /api/poc/{id}/plan).")
    manifest = poc_store.get_manifest(sid)
    if manifest:
        b.add_json("validation/poc-manifest.json", redact(manifest, env_secrets), GEN_CANDIDATES)
    else:
        b.notes.append("validation/poc-manifest.json omitted: no PoC discovery recorded.")
    runs = redact(poc_store.get_runs(sid), env_secrets)
    chain = poc_store.get_chain(sid)
    if runs or chain:
        b.add_json("validation/results.json",
                   {"scenario_id": sid, "execution_results": runs,
                    "chain_validation": redact(chain, env_secrets) if chain else None},
                   GEN_RUNS)
    else:
        b.notes.append("validation/results.json omitted: no PoC execution or chain validation recorded.")
    # Export is read-only: never call service.report()/plan(), which re-generate and persist a plan.
    # The fidelity report is derived (pure functions of poc.chain) from the STORED plan + runs only.
    fidelity = None
    if not plan:
        b.notes.append("validation/fidelity-report.json omitted: no stored ValidationPlan to report against.")
    else:
        try:
            from app.poc import chain as chain_mod
            raw_runs = poc_store.get_runs(sid)
            chain_obj = chain_mod.validate_chain(sid, ir, plan, raw_runs)
            validation_report = None
            try:
                from app.validator import runner as v_runner
                validation_report = v_runner.get_latest_report(sid)
            except Exception:
                validation_report = None
            fidelity = chain_mod.build_fidelity_report(sid, ir, plan, raw_runs, chain_obj,
                                                       validation_report=validation_report)
        except ImportError:
            b.notes.append("validation/fidelity-report.json omitted: fidelity report not available in this build.")
        except Exception as exc:
            b.notes.append(f"validation/fidelity-report.json omitted: report unavailable ({type(exc).__name__}).")
    if fidelity:
        b.add_json("validation/fidelity-report.json", redact(fidelity, env_secrets), GEN_FIDELITY)
    return runs


def _evidence_index(b: _Bundle, runs: list[dict[str, Any]]) -> None:
    root = config.DATA_DIR.resolve()
    items = []
    for run in runs:
        for ev in run.get("evidence", []) or []:
            raw = str(ev.get("path") or "")
            entry = {"action_id": run.get("action_id"), "run_status": run.get("status"),
                     "kind": ev.get("kind"), "path": raw, "sha256": ev.get("sha256"),
                     "redacted": ev.get("redacted"), "note": ev.get("note"),
                     "present_on_exporting_host": False, "sha256_verified": False}
            try:
                p = Path(raw)
                p = (p if p.is_absolute() else root / p).resolve()
                inside = p == root or root in p.parents
                if raw and inside and p.is_file():
                    entry["present_on_exporting_host"] = True
                    h = hashlib.sha256()
                    with p.open("rb") as f:
                        for chunk in iter(lambda: f.read(1 << 20), b""):
                            h.update(chunk)
                    entry["sha256_verified"] = h.hexdigest() == ev.get("sha256")
            except OSError:
                pass
            items.append(entry)
    b.add_json("evidence/evidence-index.json", {
        "scenario_id": b.scenario_id,
        "raw_evidence_included": False,
        "note": ("Index only. Raw evidence stays under the exporting host's DATA_DIR and is not copied "
                 "into the bundle (it may contain target data). sha256_verified compares the stored file "
                 "with the hash recorded at execution time."),
        "items": items,
    }, GEN_EXPORT)


